private enum class GeneratorMode(val label: String) { PASSWORD("Password"), PASSPHRASE("Passphrase") }

/**
 * Password and passphrase generator. With [onUse] set (opened from the login editor) it offers to
 * insert the result; without it (opened from the list) it is just a generator with copy.
 *
 * The generated value lives only in this dialog's memory state, never in saved state.
 */
@Composable
fun PasswordGeneratorDialog(
    onDismiss: () -> Unit,
    onUse: ((String) -> Unit)? = null
) {
    val context = LocalContext.current
    val words = remember(context) { WordList.generator(context) }
    var mode by remember { mutableStateOf(GeneratorMode.PASSWORD) }
    var options by remember { mutableStateOf(GeneratorOptions()) }
    var phraseOptions by remember { mutableStateOf(PassphraseOptions()) }
    var generated by remember { mutableStateOf(PasswordGenerator.generate(GeneratorOptions())) }
    var copied by remember { mutableStateOf(false) }

    fun regenerate() {
        generated = when (mode) {
            GeneratorMode.PASSWORD -> PasswordGenerator.generate(options)
            GeneratorMode.PASSPHRASE -> words.passphrase(phraseOptions)
        }
        copied = false
    }

    fun apply(next: GeneratorOptions) {
        // Never allow a configuration without a character set.
        if (!next.isValid) return
        options = next
        regenerate()
    }

    fun applyPhrase(next: PassphraseOptions) {
        phraseOptions = next
        regenerate()
    }

    val selectedCount = listOf(options.uppercase, options.lowercase, options.digits, options.symbols).count { it }
    val dismissButton: (@Composable () -> Unit)? = if (onUse != null) {
        { TextButton(onClick = onDismiss) { Text("Cancel") } }
    } else {
        null
    }

    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text("Generator") },
        text = {
            Column {
                SingleChoiceSegmentedButtonRow(Modifier.fillMaxWidth()) {
                    GeneratorMode.entries.forEachIndexed { index, m ->
                        SegmentedButton(
                            selected = mode == m,
                            onClick = { mode = m; regenerate() },
                            shape = SegmentedButtonDefaults.itemShape(index, GeneratorMode.entries.size)
                        ) { Text(m.label) }
                    }
                }
                Spacer(Modifier.height(14.dp))
                ResultBox(generated)
                Spacer(Modifier.height(16.dp))
                when (mode) {
                    GeneratorMode.PASSWORD -> {
                        Text("Length: ${options.length}", color = MaterialTheme.colorScheme.onSurfaceVariant, style = MaterialTheme.typography.labelLarge)
                        Slider(
                            value = options.length.toFloat(),
                            onValueChange = { apply(options.copy(length = it.roundToInt())) },
                            valueRange = GeneratorOptions.MIN_LENGTH.toFloat()..GeneratorOptions.MAX_LENGTH.toFloat(),
                            steps = GeneratorOptions.MAX_LENGTH - GeneratorOptions.MIN_LENGTH - 1
                        )
                        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                            SetChip("A-Z", options.uppercase, selectedCount) { apply(options.copy(uppercase = !options.uppercase)) }
                            SetChip("a-z", options.lowercase, selectedCount) { apply(options.copy(lowercase = !options.lowercase)) }
                            SetChip("0-9", options.digits, selectedCount) { apply(options.copy(digits = !options.digits)) }
                            SetChip("#$%", options.symbols, selectedCount) { apply(options.copy(symbols = !options.symbols)) }
                        }
                    }
                    GeneratorMode.PASSPHRASE -> {
                        Text(
                            "Words: ${phraseOptions.words}  ·  about ${words.entropyBits(phraseOptions)} bits",
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            style = MaterialTheme.typography.labelLarge
                        )
                        Slider(
                            value = phraseOptions.words.toFloat(),
                            onValueChange = { applyPhrase(phraseOptions.copy(words = it.roundToInt())) },
                            valueRange = PassphraseOptions.MIN_WORDS.toFloat()..PassphraseOptions.MAX_WORDS.toFloat(),
                            steps = PassphraseOptions.MAX_WORDS - PassphraseOptions.MIN_WORDS - 1
                        )
                        Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                            PassphraseOptions.SEPARATORS.forEach { sep ->
                                FilterChip(
                                    selected = phraseOptions.separator == sep,
                                    onClick = { applyPhrase(phraseOptions.copy(separator = sep)) },
                                    label = { Text(when (sep) { " " -> "space"; "" -> "none"; else -> sep }) }
                                )
                            }
                        }
                        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                            FilterChip(
                                selected = phraseOptions.capitalize,
                                onClick = { applyPhrase(phraseOptions.copy(capitalize = !phraseOptions.capitalize)) },
                                label = { Text("Capitals") }
                            )
                            FilterChip(
                                selected = phraseOptions.addNumber,
                                onClick = { applyPhrase(phraseOptions.copy(addNumber = !phraseOptions.addNumber)) },
                                label = { Text("Number") }
                            )
                        }
                    }
                }
                Row(horizontalArrangement = Arrangement.spacedBy(4.dp)) {
                    TextButton(onClick = { regenerate() }) { Text("Generate") }
                    TextButton(onClick = {
                        ClipboardGuard.copySensitive(context, generated)
                        copied = true
                    }) { Text(if (copied) "Copied" else "Copy") }
                }
            }
        },
        confirmButton = {
            if (onUse != null) {
                TextButton(onClick = { onUse(generated) }) { Text("Use") }
            } else {
                TextButton(onClick = onDismiss) { Text("Close") }
            }
        },
        dismissButton = dismissButton
    )
}

/**
 * Suggests a username: two words and a number, random characters, or an alias of the user's email
 * address ("name+word42@example.com").
 */
@Composable
fun UsernameGeneratorDialog(onDismiss: () -> Unit, onUse: (String) -> Unit) {
    val context = LocalContext.current
    val words = remember(context) { WordList.generator(context) }
    var style by remember { mutableStateOf(UsernameStyle.WORDS) }
    var email by remember { mutableStateOf("") }
    var generated by remember { mutableStateOf(words.username(UsernameStyle.WORDS)) }

    fun regenerate() {
        generated = words.username(style, email.trim())
    }

    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text("Username generator") },
        text = {
            Column {
                Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    listOf(UsernameStyle.WORDS to "Words", UsernameStyle.RANDOM to "Random", UsernameStyle.EMAIL_ALIAS to "Email alias")
                        .forEach { (s, label) ->
                            FilterChip(selected = style == s, onClick = { style = s; regenerate() }, label = { Text(label) })
                        }
                }
                if (style == UsernameStyle.EMAIL_ALIAS) {
                    OutlinedTextField(
                        value = email,
                        onValueChange = { email = it; regenerate() },
                        label = { Text("Your email address") },
                        singleLine = true,
                        modifier = Modifier.fillMaxWidth().padding(top = 8.dp)
                    )
                    Text(
                        "Most email providers deliver name+anything@ to your normal inbox, so each site gets its own address.",
                        modifier = Modifier.padding(top = 6.dp),
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        style = MaterialTheme.typography.bodySmall
                    )
                }
                Spacer(Modifier.height(12.dp))
                ResultBox(generated.ifEmpty { "Enter your email address" })
                TextButton(onClick = { regenerate() }) { Text("Generate") }
            }
        },
        confirmButton = { TextButton(onClick = { onUse(generated) }, enabled = generated.isNotEmpty()) { Text("Use") } },
        dismissButton = { TextButton(onClick = onDismiss) { Text("Cancel") } }
    )
}

@Composable
private fun ResultBox(text: String) {
    Surface(
        modifier = Modifier.fillMaxWidth(),
        shape = RoundedCornerShape(12.dp),
        color = MaterialTheme.colorScheme.surfaceContainer
    ) {
        Text(
            text = text,
            modifier = Modifier.padding(14.dp),
            color = MaterialTheme.colorScheme.onSurface,
            style = MaterialTheme.typography.bodyLarge.copy(fontFamily = FontFamily.Monospace)
        )
    }
}

/** A character-set toggle. The last remaining set cannot be switched off. */
@Composable
private fun SetChip(label: String, selected: Boolean, selectedCount: Int, onClick: () -> Unit) {
    FilterChip(
        selected = selected,
        onClick = onClick,
        enabled = !(selected && selectedCount == 1),
        label = { Text(label) }
    )
}
