/**
 * Password generator. With [onUse] set (opened from the login editor) it offers to insert the
 * result; without it (opened from the list) it is just a generator with copy.
 *
 * The generated value lives only in this dialog's memory state, never in saved state.
 */
@Composable
fun PasswordGeneratorDialog(
    onDismiss: () -> Unit,
    onUse: ((String) -> Unit)? = null
) {
    val context = LocalContext.current
    var options by remember { mutableStateOf(GeneratorOptions()) }
    var generated by remember { mutableStateOf(PasswordGenerator.generate(GeneratorOptions())) }
    var copied by remember { mutableStateOf(false) }

    fun apply(next: GeneratorOptions) {
        // Never allow a configuration without a character set.
        if (!next.isValid) return
        options = next
        generated = PasswordGenerator.generate(next)
        copied = false
    }

    val selectedCount = listOf(options.uppercase, options.lowercase, options.digits, options.symbols).count { it }
    val dismissButton: (@Composable () -> Unit)? = if (onUse != null) {
        { TextButton(onClick = onDismiss) { Text("Cancel") } }
    } else {
        null
    }

    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text("Password generator") },
        text = {
            Column {
                Surface(
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(12.dp),
                    color = MaterialTheme.colorScheme.surfaceContainer
                ) {
                    Text(
                        text = generated,
                        modifier = Modifier.padding(14.dp),
                        color = MaterialTheme.colorScheme.onSurface,
                        style = MaterialTheme.typography.bodyLarge.copy(fontFamily = FontFamily.Monospace)
                    )
                }
                Spacer(Modifier.height(16.dp))
                Text(
                    text = "Length: ${options.length}",
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    style = MaterialTheme.typography.labelLarge
                )
                Slider(
                    value = options.length.toFloat(),
                    onValueChange = { apply(options.copy(length = it.roundToInt())) },
                    valueRange = GeneratorOptions.MIN_LENGTH.toFloat()..GeneratorOptions.MAX_LENGTH.toFloat(),
                    steps = GeneratorOptions.MAX_LENGTH - GeneratorOptions.MIN_LENGTH - 1
                )
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    SetChip("A-Z", options.uppercase, selectedCount) { apply(options.copy(uppercase = !options.uppercase)) }
                    SetChip("a-z", options.lowercase, selectedCount) { apply(options.copy(lowercase = !options.lowercase)) }
                    SetChip("0-9", options.digits, selectedCount) { apply(options.copy(digits = !options.digits)) }
                    SetChip("#$%", options.symbols, selectedCount) { apply(options.copy(symbols = !options.symbols)) }
                }
                Row(horizontalArrangement = Arrangement.spacedBy(4.dp)) {
                    TextButton(onClick = { apply(options) }) { Text("Generate") }
                    TextButton(onClick = {
                        ClipboardGuard.copySensitive(context, generated)
                        copied = true
                    }) { Text(if (copied) "Copied" else "Copy") }
                }
            }
        },
        confirmButton = {
            if (onUse != null) {
                TextButton(onClick = { onUse(generated) }) { Text("Use password") }
            } else {
                TextButton(onClick = onDismiss) { Text("Close") }
            }
        },
        dismissButton = dismissButton
    )
}

/** A character-set toggle. The last remaining set cannot be switched off. */
@Composable
private fun SetChip(label: String, selected: Boolean, selectedCount: Int, onClick: () -> Unit) {
    FilterChip(
        selected = selected,
        onClick = onClick,
        enabled = !(selected && selectedCount == 1),
        label = { Text(label) }
    )
}
